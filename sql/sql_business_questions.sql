-- Q19: Customers with month-over-month viewing time decline
-- Only compares consecutive calendar months
-- ============================================================
WITH monthly_watch AS (
    SELECT
        customer_id,
        DATE_TRUNC('month', viewing_date)::DATE AS month,
        SUM(watch_duration_minutes) AS monthly_watch_minutes
    FROM viewing_activity
    WHERE viewing_date IS NOT NULL
    GROUP BY customer_id, DATE_TRUNC('month', viewing_date)
),
latest_month AS (
    SELECT
        customer_id,
        MAX(month) AS latest_month
    FROM monthly_watch
    GROUP BY customer_id
),
comparison AS (
    SELECT
        current_month.customer_id,
        current_month.month,
        current_month.monthly_watch_minutes,
        previous_month.monthly_watch_minutes AS previous_month_minutes
    FROM latest_month lm
    JOIN monthly_watch current_month
      ON current_month.customer_id = lm.customer_id
     AND current_month.month = lm.latest_month
    JOIN monthly_watch previous_month
      ON previous_month.customer_id = current_month.customer_id
     AND previous_month.month =
         (current_month.month - INTERVAL '1 month')::DATE
)
SELECT
    customer_id,
    month AS most_recent_viewing_month,
    monthly_watch_minutes,
    previous_month_minutes,
    previous_month_minutes - monthly_watch_minutes AS decline_minutes
FROM comparison
WHERE monthly_watch_minutes < previous_month_minutes
ORDER BY decline_minutes DESC;

-- Q20: Acquisition cohort retention at 1, 3 and 6 months
-- Active = subscription window covers the cohort milestone date
-- ============================================================
WITH cohorts AS (
    SELECT
        customer_id,
        DATE_TRUNC('month', registration_date)::DATE AS cohort_month,
        registration_date
    FROM customers
    WHERE registration_date IS NOT NULL
),
cohort_sizes AS (
    SELECT cohort_month, COUNT(*) AS cohort_size
    FROM cohorts
    GROUP BY cohort_month
),
milestones AS (
    SELECT
        c.cohort_month,
        cs.cohort_size,
        c.customer_id,
        m.month_number,
        (c.registration_date + make_interval(months => m.month_number))::DATE
            AS milestone_date
    FROM cohorts c
    JOIN cohort_sizes cs USING (cohort_month)
    CROSS JOIN (VALUES (1), (3), (6)) AS m(month_number)
),
retained AS (
    SELECT
        m.cohort_month,
        m.cohort_size,
        m.month_number,
        COUNT(DISTINCT m.customer_id) FILTER (
            WHERE EXISTS (
                SELECT 1
                FROM subscriptions s
                WHERE s.customer_id = m.customer_id
                  AND s.subscription_start_date <= m.milestone_date
                  AND (
                      s.subscription_end_date IS NULL
                      OR s.subscription_end_date > m.milestone_date
                  )
                  AND s.subscription_status <> 'Cancelled'
            )
        ) AS retained_customers
    FROM milestones m
    GROUP BY m.cohort_month, m.cohort_size, m.month_number
)
SELECT
    cohort_month,
    month_number,
    cohort_size,
    retained_customers,
    ROUND(retained_customers * 100.0 / NULLIF(cohort_size, 0), 2)
        AS retention_percentage
FROM retained
ORDER BY cohort_month, month_number;

-- Q21: Top 5 countries by churn rate using DENSE_RANK
