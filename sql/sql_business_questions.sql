-- Q11: Device type generating the most viewing minutes
-- Device labels normalized into standard categories
-- ============================================================
WITH normalized_devices AS (
    SELECT
        CASE
            WHEN LOWER(TRIM(device_type)) IN ('smart tv', 'smarttv', 'tv')
                THEN 'Smart TV'
            WHEN LOWER(TRIM(device_type)) IN ('mobile', 'smartphone', 'phone')
                THEN 'Mobile'
            WHEN LOWER(TRIM(device_type)) = 'laptop'
                THEN 'Laptop'
            WHEN LOWER(TRIM(device_type)) IN ('desktop', 'pc')
                THEN 'Desktop'
            WHEN LOWER(TRIM(device_type)) IN ('tablet', 'ipad')
                THEN 'Tablet'
            WHEN LOWER(TRIM(device_type)) IN
                ('gaming console', 'console', 'playstation/xbox')
                THEN 'Gaming Console'
            ELSE 'Unknown'
        END AS device_type,
        watch_duration_minutes,
        customer_id
    FROM viewing_activity
)
SELECT
    device_type,
    SUM(watch_duration_minutes) AS total_watch_minutes,
    COUNT(*) AS viewing_sessions,
    COUNT(DISTINCT customer_id) AS unique_viewers
FROM normalized_devices
GROUP BY device_type
ORDER BY total_watch_minutes DESC;

