-- Q23: Customers with declining watch time for 3 consecutive months
-- ============================================================
WITH monthly_watch AS (
    SELECT
        customer_id,
        DATE_TRUNC('month', viewing_date)::DATE AS month,
        SUM(watch_duration_minutes) AS watch_minutes
    FROM viewing_activity
    GROUP BY customer_id, DATE_TRUNC('month', viewing_date)
),
trends AS (
    SELECT
        customer_id,
        month,
        watch_minutes,
        LAG(watch_minutes, 1) OVER (
            PARTITION BY customer_id ORDER BY month
        ) AS previous_month,
        LAG(watch_minutes, 2) OVER (
            PARTITION BY customer_id ORDER BY month
        ) AS two_months_ago,
        LAG(month, 1) OVER (
            PARTITION BY customer_id ORDER BY month
        ) AS previous_month_date,
        LAG(month, 2) OVER (
            PARTITION BY customer_id ORDER BY month
        ) AS two_months_ago_date
    FROM monthly_watch
)
SELECT
    customer_id,
    two_months_ago_date,
    previous_month_date,
    month AS latest_month,
    two_months_ago AS month_1_watch_minutes,
    previous_month AS month_2_watch_minutes,
    watch_minutes AS month_3_watch_minutes
FROM trends
WHERE previous_month_date = month - INTERVAL '1 month'
  AND two_months_ago_date = month - INTERVAL '2 months'
  AND watch_minutes < previous_month
  AND previous_month < two_months_ago
ORDER BY customer_id, month;

-- Q24: Monthly churn rate for last 12 months
-- Denominator = customers with a valid subscription active at month start.
-- Cancellation and subscription end dates use exclusive boundaries.
-- Invalid cancellation dates before subscription start are excluded.
-- ============================================================
WITH months AS (
    SELECT
        GENERATE_SERIES(
            DATE_TRUNC('month', MAX(churn_date)) - INTERVAL '11 months',
            DATE_TRUNC('month', MAX(churn_date)),
            INTERVAL '1 month'
        )::DATE AS month_start
    FROM churn_labels
    WHERE churn_date IS NOT NULL
),
monthly_metrics AS (
    SELECT
        m.month_start,
        COUNT(DISTINCT s.customer_id) FILTER (
            WHERE s.subscription_start_date <= m.month_start
              AND (
                  s.subscription_end_date IS NULL
                  OR s.subscription_end_date > m.month_start
              )
              AND (
                  s.cancellation_date IS NULL
                  OR s.cancellation_date > m.month_start
              )
              AND (
                  s.cancellation_date IS NULL
                  OR s.cancellation_date >= s.subscription_start_date
              )
        ) AS active_at_month_start,
        COUNT(DISTINCT cl.customer_id) FILTER (
            WHERE cl.churn_date >= m.month_start
              AND cl.churn_date < m.month_start + INTERVAL '1 month'
        ) AS churned_in_month
    FROM months m
    LEFT JOIN subscriptions s ON TRUE
    LEFT JOIN churn_labels cl
        ON cl.customer_id = s.customer_id
       AND cl.churned = TRUE
    GROUP BY m.month_start
)
SELECT
    month_start,
    active_at_month_start,
    churned_in_month,
    ROUND(
        churned_in_month * 100.0
        / NULLIF(active_at_month_start, 0),
        2
    ) AS monthly_churn_rate_pct
FROM monthly_metrics
ORDER BY month_start;

-- Q25: Customer retention by acquisition channel
-- Active today = latest subscription status Active and no end date
-- ============================================================
WITH latest_subscription AS (
