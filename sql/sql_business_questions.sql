-- Q28: 2+ failed payments in last 90 days and high churn risk
-- SQL risk proxy is used because no prediction table is in schema.
-- Proxy: recent failed payments + declining engagement + tickets.
-- ============================================================
WITH latest_data AS (
    SELECT MAX(payment_date) AS max_payment_date FROM payments
),
failed AS (
    SELECT
        p.customer_id,
        COUNT(*) AS failed_payment_count
    FROM payments p
    CROSS JOIN latest_data d
    WHERE p.payment_status = 'Failed'
      AND p.payment_date > d.max_payment_date - INTERVAL '90 days'
      AND p.payment_date <= d.max_payment_date
    GROUP BY p.customer_id
    HAVING COUNT(*) >= 2
),
latest_plan AS (
    SELECT
        customer_id,
        plan_id,
        ROW_NUMBER() OVER (
            PARTITION BY customer_id
            ORDER BY subscription_start_date DESC, subscription_id DESC
        ) AS rn
    FROM subscriptions
),
engagement AS (
    SELECT
        customer_id,
        MAX(viewing_date) AS last_viewing_date
    FROM viewing_activity
    GROUP BY customer_id
),
tickets AS (
    SELECT customer_id, COUNT(*) AS ticket_count
    FROM support_tickets
    GROUP BY customer_id
),
risk AS (
    SELECT
        f.customer_id,
        f.failed_payment_count,
        lp.plan_id,
        COALESCE(CURRENT_DATE - e.last_viewing_date, 9999) AS days_inactive,
        COALESCE(t.ticket_count, 0) AS ticket_count
    FROM failed f
    LEFT JOIN latest_plan lp ON lp.customer_id = f.customer_id AND lp.rn = 1
    LEFT JOIN engagement e ON e.customer_id = f.customer_id
    LEFT JOIN tickets t ON t.customer_id = f.customer_id
)
SELECT
    r.customer_id,
    r.failed_payment_count,
    sp.plan_name AS current_plan,
    r.days_inactive,
    r.ticket_count,
    (
        r.failed_payment_count * 2
        + CASE WHEN r.days_inactive > 30 THEN 2 ELSE 0 END
        + CASE WHEN r.ticket_count >= 3 THEN 1 ELSE 0 END
    ) AS sql_churn_risk_proxy
FROM risk r
LEFT JOIN subscription_plans sp ON sp.plan_id = r.plan_id
WHERE (
        r.failed_payment_count * 2
        + CASE WHEN r.days_inactive > 30 THEN 2 ELSE 0 END
        + CASE WHEN r.ticket_count >= 3 THEN 1 ELSE 0 END
      ) >= 4
ORDER BY sql_churn_risk_proxy DESC, failed_payment_count DESC;

-- Q29: Engagement 30 days before and after latest price change
-- ============================================================
WITH subscription_history AS (
    SELECT
        customer_id,
        subscription_start_date AS change_date,
        monthly_price,
        LAG(monthly_price) OVER (
            PARTITION BY customer_id
            ORDER BY subscription_start_date
        ) AS previous_price
    FROM subscriptions
),
price_changes AS (
    SELECT *
    FROM (
        SELECT *,
            ROW_NUMBER() OVER (
                PARTITION BY customer_id
                ORDER BY change_date DESC
            ) AS rn
        FROM subscription_history
        WHERE previous_price IS NOT NULL
          AND monthly_price <> previous_price
    ) x
    WHERE rn = 1
),
engagement AS (
    SELECT
        pc.customer_id,
        pc.change_date,
        pc.previous_price,
        pc.monthly_price,
        AVG(va.watch_duration_minutes) FILTER (
            WHERE va.viewing_date >= pc.change_date - INTERVAL '30 days'
              AND va.viewing_date < pc.change_date
        ) AS avg_watch_before,
        AVG(va.watch_duration_minutes) FILTER (
            WHERE va.viewing_date >= pc.change_date
              AND va.viewing_date < pc.change_date + INTERVAL '30 days'
        ) AS avg_watch_after
    FROM price_changes pc
    LEFT JOIN viewing_activity va
        ON va.customer_id = pc.customer_id
       AND va.viewing_date >= pc.change_date - INTERVAL '30 days'
       AND va.viewing_date < pc.change_date + INTERVAL '30 days'
    GROUP BY
        pc.customer_id, pc.change_date,
        pc.previous_price, pc.monthly_price
)
SELECT
    *,
    ROUND(
        (avg_watch_after - avg_watch_before) * 100.0
        / NULLIF(avg_watch_before, 0),
        2
    ) AS engagement_change_pct
FROM engagement
ORDER BY engagement_change_pct;

-- Q30: Country-level churn, CLV of churned customers, top reason
-- CLV = sum of successful payments before/on churn date
-- ============================================================
WITH customer_value AS (
    SELECT
        c.customer_id,
        COALESCE(ccn.normalized_country, 'Unknown') AS country,
        cl.churned,
        cl.churn_date,
        cl.churn_reason,
        COALESCE(SUM(p.amount) FILTER (
            WHERE p.payment_status = 'Success'
              AND (cl.churn_date IS NULL OR p.payment_date <= cl.churn_date)
        ), 0) AS customer_lifetime_value
    FROM customers c
    JOIN churn_labels cl USING (customer_id)
    LEFT JOIN customer_country_normalized ccn USING (customer_id)
    LEFT JOIN payments p ON p.customer_id = c.customer_id
    GROUP BY
        c.customer_id, ccn.normalized_country,
        cl.churned, cl.churn_date, cl.churn_reason
),
country_metrics AS (
    SELECT
        country,
        COUNT(*) AS total_customers,
        COUNT(*) FILTER (WHERE churned = TRUE) AS churned_customers,
        ROUND(
            COUNT(*) FILTER (WHERE churned = TRUE) * 100.0
            / NULLIF(COUNT(*), 0),
            2
        ) AS churn_rate_pct,
        ROUND(AVG(customer_lifetime_value) FILTER (WHERE churned = TRUE), 2)
            AS avg_clv_per_churned_customer
    FROM customer_value
    GROUP BY country
),
reason_counts AS (
    SELECT
        country,
        churn_reason,
        COUNT(*) AS reason_count,
        ROW_NUMBER() OVER (
            PARTITION BY country ORDER BY COUNT(*) DESC, churn_reason
        ) AS rn
    FROM customer_value
    WHERE churned = TRUE AND churn_reason IS NOT NULL
    GROUP BY country, churn_reason
)
SELECT
    cm.*,
    rc.churn_reason AS top_churn_reason
FROM country_metrics cm
LEFT JOIN reason_counts rc
    ON rc.country = cm.country AND rc.rn = 1
ORDER BY cm.churn_rate_pct DESC;

-- Q31: At-risk revenue report, top 50 active customers
-- Composite SQL risk proxy; normalized features 0 to 1
-- ============================================================
WITH latest_subscription AS (
    SELECT
        s.*,
        ROW_NUMBER() OVER (
            PARTITION BY customer_id
            ORDER BY subscription_start_date DESC, subscription_id DESC
        ) AS rn
    FROM subscriptions s
    WHERE subscription_status = 'Active'
      AND subscription_end_date IS NULL
),
engagement AS (
    SELECT
        customer_id,
        MAX(viewing_date) AS last_activity_date
    FROM viewing_activity
    GROUP BY customer_id
),
payments AS (
    SELECT
        customer_id,
        COUNT(*) FILTER (WHERE payment_status = 'Failed') AS failed_count,
        COUNT(*) AS total_payment_count
    FROM payments
    GROUP BY customer_id
),
tickets AS (
    SELECT customer_id, COUNT(*) AS ticket_count
    FROM support_tickets
    GROUP BY customer_id
),
base AS (
    SELECT
        s.customer_id,
        s.monthly_price,
        COALESCE(CURRENT_DATE - e.last_activity_date, 365) AS days_inactive,
        COALESCE(p.failed_count::NUMERIC / NULLIF(p.total_payment_count, 0), 0)
            AS failed_payment_rate,
        COALESCE(t.ticket_count, 0) AS ticket_count
    FROM latest_subscription s
    LEFT JOIN engagement e ON e.customer_id = s.customer_id
    LEFT JOIN payments p ON p.customer_id = s.customer_id
    LEFT JOIN tickets t ON t.customer_id = s.customer_id
    WHERE s.rn = 1
),
normalized AS (
    SELECT *,
        COALESCE(
            (days_inactive - MIN(days_inactive) OVER ())::NUMERIC
            / NULLIF(MAX(days_inactive) OVER () - MIN(days_inactive) OVER (), 0),
            0
        ) AS recency_score,
        COALESCE(
            (failed_payment_rate - MIN(failed_payment_rate) OVER ())
            / NULLIF(MAX(failed_payment_rate) OVER () - MIN(failed_payment_rate) OVER (), 0),
            0
        ) AS payment_risk_score,
        COALESCE(
            (ticket_count - MIN(ticket_count) OVER ())::NUMERIC
            / NULLIF(MAX(ticket_count) OVER () - MIN(ticket_count) OVER (), 0),
            0
        ) AS support_risk_score
    FROM base
),
scored AS (
    SELECT *,
        ROUND(
            (recency_score * 0.4
             + payment_risk_score * 0.35
             + support_risk_score * 0.25) * 100,
            2
        ) AS churn_risk_score
    FROM normalized
)
SELECT
    customer_id,
    days_inactive,
    failed_payment_rate,
    ticket_count,
    monthly_price,
    churn_risk_score,
    ROUND(monthly_price * churn_risk_score / 100.0, 2)
        AS at_risk_monthly_revenue
FROM scored
ORDER BY at_risk_monthly_revenue DESC
LIMIT 50;

-- Q32: Top 5 complaints per country in most recent completed quarter
-- ============================================================
WITH latest_ticket_date AS (
    SELECT MAX(ticket_date) AS max_date FROM support_tickets
),
quarter_window AS (
    SELECT
        DATE_TRUNC('quarter', max_date) - INTERVAL '3 months' AS start_date,
        DATE_TRUNC('quarter', max_date) AS end_date
    FROM latest_ticket_date
),
complaints AS (
    SELECT
        COALESCE(ccn.normalized_country, 'Unknown') AS country,
        st.issue_subcategory,
        COUNT(*) AS ticket_volume,
        ROUND(AVG(st.resolution_time_hours), 2) AS avg_resolution_hours,
        ROUND(AVG(st.customer_satisfaction_score), 2) AS avg_satisfaction
    FROM support_tickets st
    JOIN customers c USING (customer_id)
    LEFT JOIN customer_country_normalized ccn USING (customer_id)
    CROSS JOIN quarter_window q
    WHERE st.ticket_date >= q.start_date
      AND st.ticket_date < q.end_date
      AND st.issue_subcategory IS NOT NULL
    GROUP BY 1, 2
),
ranked AS (
    SELECT *,
        ROW_NUMBER() OVER (
            PARTITION BY country ORDER BY ticket_volume DESC, issue_subcategory
        ) AS complaint_rank
    FROM complaints
)
SELECT *
FROM ranked
WHERE complaint_rank <= 5
ORDER BY country, complaint_rank;

-- Q33: Win-back candidates: churned customers in top CLV quartile
-- ============================================================
WITH churned_value AS (
    SELECT
        c.customer_id,
        cl.churn_reason,
        cl.churn_date,
        COALESCE(SUM(p.amount) FILTER (
            WHERE p.payment_status = 'Success'
              AND (cl.churn_date IS NULL OR p.payment_date <= cl.churn_date)
        ), 0) AS customer_lifetime_value
    FROM customers c
    JOIN churn_labels cl USING (customer_id)
    LEFT JOIN payments p ON p.customer_id = c.customer_id
    WHERE cl.churned = TRUE
      AND cl.churn_date IS NOT NULL
    GROUP BY c.customer_id, cl.churn_reason, cl.churn_date
),
quartiles AS (
    SELECT *,
        NTILE(4) OVER (ORDER BY customer_lifetime_value DESC) AS clv_quartile
    FROM churned_value
),
last_engagement AS (
    SELECT
        va.customer_id,
        MAX(va.viewing_date) AS last_viewing_date,
        SUM(va.watch_duration_minutes) AS total_watch_minutes
    FROM viewing_activity va
    JOIN churned_value cv
        ON cv.customer_id = va.customer_id
    WHERE va.viewing_date <= cv.churn_date
    GROUP BY va.customer_id
)
SELECT
    q.customer_id,
    q.customer_lifetime_value,
    q.churn_reason,
    q.churn_date,
    le.last_viewing_date,
    le.total_watch_minutes,
    CASE
        WHEN le.last_viewing_date IS NULL THEN 'No viewing history'
        WHEN q.churn_date - le.last_viewing_date <= 30 THEN 'High engagement near churn'
        WHEN q.churn_date - le.last_viewing_date <= 90 THEN 'Moderate engagement near churn'
        ELSE 'Low engagement near churn'
    END AS last_known_engagement_level
FROM quartiles q
LEFT JOIN last_engagement le USING (customer_id)
WHERE q.clv_quartile = 1
ORDER BY q.customer_lifetime_value DESC;

-- Q34: Actual plan migration paths and migration-level churn
-- ============================================================
WITH ordered_plans AS (
    SELECT
        s.customer_id,
        s.plan_id,
        sp.plan_name,
        sp.monthly_price,
        s.subscription_start_date,
        LAG(s.plan_id) OVER (
            PARTITION BY s.customer_id
            ORDER BY s.subscription_start_date, s.subscription_id
        ) AS previous_plan_id,
        LAG(sp.plan_name) OVER (
            PARTITION BY s.customer_id
            ORDER BY s.subscription_start_date, s.subscription_id
        ) AS previous_plan,
        LAG(sp.monthly_price) OVER (
            PARTITION BY s.customer_id
            ORDER BY s.subscription_start_date, s.subscription_id
        ) AS previous_price
    FROM subscriptions s
    JOIN subscription_plans sp USING (plan_id)
),
migrations AS (
    SELECT
        customer_id,
        previous_plan,
        plan_name AS new_plan,
        previous_price,
        monthly_price,
        CASE
            WHEN monthly_price > previous_price THEN 'Upgrader'
            WHEN monthly_price < previous_price THEN 'Downgrader'
            ELSE 'Same price'
        END AS migration_type
    FROM ordered_plans
    WHERE previous_plan_id IS NOT NULL
      AND plan_id <> previous_plan_id
),
customer_migration AS (
    SELECT
        m.*,
        COALESCE(cl.churned, FALSE) AS churned
    FROM migrations m
    LEFT JOIN churn_labels cl USING (customer_id)
)
SELECT
    previous_plan || ' -> ' || new_plan AS migration_path,
    migration_type,
    COUNT(*) AS migration_events,
    COUNT(DISTINCT customer_id) AS unique_customers,
    COUNT(DISTINCT customer_id) FILTER (
        WHERE churned = TRUE
    ) AS churned_customers,
    ROUND(
        COUNT(DISTINCT customer_id) FILTER (WHERE churned = TRUE) * 100.0
        / NULLIF(COUNT(DISTINCT customer_id), 0),
        2
    ) AS customer_churn_rate_pct
FROM customer_migration
GROUP BY previous_plan, new_plan, migration_type
ORDER BY migration_events DESC;

-- Q35: WAU, MAU and WAU/MAU stickiness over last 6 months
-- ============================================================
WITH latest_date AS (
    SELECT MAX(viewing_date) AS max_date FROM viewing_activity
),
weekly AS (
    SELECT
        DATE_TRUNC('week', va.viewing_date)::DATE AS week_start,
        COUNT(DISTINCT va.customer_id) AS wau
    FROM viewing_activity va
    CROSS JOIN latest_date d
    WHERE va.viewing_date >= DATE_TRUNC('month', d.max_date) - INTERVAL '5 months'
      AND va.viewing_date <= d.max_date
    GROUP BY 1
),
monthly AS (
    SELECT
        DATE_TRUNC('month', va.viewing_date)::DATE AS month_start,
        COUNT(DISTINCT va.customer_id) AS mau
    FROM viewing_activity va
    CROSS JOIN latest_date d
    WHERE va.viewing_date >= DATE_TRUNC('month', d.max_date) - INTERVAL '5 months'
      AND va.viewing_date <= d.max_date
    GROUP BY 1
)
SELECT
    m.month_start,
    m.mau,
    ROUND(AVG(w.wau), 2) AS average_weekly_active_users,
    ROUND(AVG(w.wau) / NULLIF(m.mau, 0), 4) AS wau_mau_stickiness
FROM monthly m
LEFT JOIN weekly w
    ON w.week_start >= m.month_start
   AND w.week_start < m.month_start + INTERVAL '1 month'
GROUP BY m.month_start, m.mau
ORDER BY m.month_start;

-- Q36: Negative feedback within 14 days of failed payment
-- or ticket CSAT <= 2
-- ============================================================
WITH negative_feedback AS (
    SELECT
        feedback_id,
        customer_id,
        feedback_date,
        rating,
        sentiment_label,
        feedback_text
    FROM customer_feedback
    WHERE LOWER(COALESCE(sentiment_label, '')) = 'negative'
       OR rating <= 2
),
trigger_events AS (
    SELECT
        customer_id,
        payment_date AS event_date,
        'Failed payment' AS trigger_type
    FROM payments
    WHERE payment_status = 'Failed'

    UNION ALL

    SELECT
        customer_id,
        ticket_date AS event_date,
        'Low support satisfaction' AS trigger_type
    FROM support_tickets
    WHERE customer_satisfaction_score <= 2
      AND ticket_date IS NOT NULL
)
SELECT DISTINCT
    nf.customer_id,
    nf.feedback_id,
    nf.feedback_date,
    nf.rating,
    nf.sentiment_label,
    te.trigger_type,
    te.event_date
FROM negative_feedback nf
JOIN trigger_events te
    ON te.customer_id = nf.customer_id
   AND nf.feedback_date BETWEEN te.event_date AND te.event_date + 14
ORDER BY nf.feedback_date DESC, nf.customer_id;

-- Q37: Full customer health score, normalized 0 to 100
-- Higher score = higher churn risk
-- ============================================================
WITH latest_subscription AS (
    SELECT
        s.customer_id,
        s.plan_id,
        s.monthly_price,
        s.subscription_start_date,
        ROW_NUMBER() OVER (
            PARTITION BY s.customer_id
            ORDER BY s.subscription_start_date DESC, s.subscription_id DESC
        ) AS rn
    FROM subscriptions s
    WHERE s.subscription_status = 'Active'
      AND s.subscription_end_date IS NULL
),
engagement AS (
    SELECT
        customer_id,
        MAX(viewing_date) AS last_viewing_date
    FROM viewing_activity
    GROUP BY customer_id
),
payment_metrics AS (
    SELECT
        customer_id,
        COUNT(*) AS total_payments,
        COUNT(*) FILTER (WHERE payment_status = 'Failed') AS failed_payments
    FROM payments
    GROUP BY customer_id
),
support_metrics AS (
    SELECT
        customer_id,
        AVG(customer_satisfaction_score) AS avg_satisfaction
    FROM support_tickets
    WHERE customer_satisfaction_score IS NOT NULL
    GROUP BY customer_id
),
base AS (
    SELECT
        c.customer_id,
        c.registration_date,
        sp.plan_name AS current_plan,
        COALESCE(CURRENT_DATE - e.last_viewing_date, 365) AS days_since_last_activity,
        COALESCE(
            pm.failed_payments::NUMERIC / NULLIF(pm.total_payments, 0),
            0
        ) AS payment_failure_rate,
        COALESCE(sm.avg_satisfaction, 3) AS avg_support_satisfaction,
        COALESCE(CURRENT_DATE - c.registration_date, 0) AS tenure_days
    FROM customers c
    LEFT JOIN latest_subscription ls
        ON ls.customer_id = c.customer_id AND ls.rn = 1
    LEFT JOIN subscription_plans sp ON sp.plan_id = ls.plan_id
    LEFT JOIN engagement e ON e.customer_id = c.customer_id
    LEFT JOIN payment_metrics pm ON pm.customer_id = c.customer_id
    LEFT JOIN support_metrics sm ON sm.customer_id = c.customer_id
),
normalized AS (
    SELECT *,
        COALESCE(
            (days_since_last_activity - MIN(days_since_last_activity) OVER ())::NUMERIC
            / NULLIF(
                MAX(days_since_last_activity) OVER ()
                - MIN(days_since_last_activity) OVER (), 0
            ),
            0
        ) AS recency_risk,
        COALESCE(
            (payment_failure_rate - MIN(payment_failure_rate) OVER ())
            / NULLIF(
                MAX(payment_failure_rate) OVER ()
                - MIN(payment_failure_rate) OVER (), 0
            ),
            0
        ) AS payment_risk,
        COALESCE(
            (MAX(avg_support_satisfaction) OVER () - avg_support_satisfaction)
            / NULLIF(
                MAX(avg_support_satisfaction) OVER ()
                - MIN(avg_support_satisfaction) OVER (), 0
            ),
            0
        ) AS support_risk,
        COALESCE(
            (MAX(tenure_days) OVER () - tenure_days)::NUMERIC
            / NULLIF(MAX(tenure_days) OVER () - MIN(tenure_days) OVER (), 0),
            0
        ) AS tenure_risk
    FROM base
)
SELECT
    customer_id,
    current_plan,
    days_since_last_activity,
    payment_failure_rate,
    ROUND(avg_support_satisfaction, 2) AS avg_support_satisfaction,
    tenure_days,
    ROUND(
        (
            recency_risk * 0.35
            + payment_risk * 0.30
            + support_risk * 0.20
            + tenure_risk * 0.15
        ) * 100,
        2
    ) AS customer_health_risk_score
FROM normalized
ORDER BY customer_health_risk_score DESC;
