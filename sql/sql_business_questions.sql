-- Q01: Current active customers by country
WITH latest_subscription AS (
    SELECT
        customer_id,
        subscription_status,
        ROW_NUMBER() OVER (
            PARTITION BY customer_id
            ORDER BY subscription_start_date DESC,
                     subscription_id DESC
        ) AS rn
    FROM subscriptions
)
SELECT
    ccn.normalized_country AS country,
    COUNT(DISTINCT ccn.customer_id) AS active_customers
FROM customer_country_normalized ccn
INNER JOIN latest_subscription ls
    ON ccn.customer_id = ls.customer_id
WHERE ls.rn = 1
  AND ls.subscription_status = 'Active'
GROUP BY ccn.normalized_country
ORDER BY active_customers DESC;

-- Q02: What is the total and average monthly revenue
-- generated by each subscription plan?
-- ============================================================
WITH payment_plan_mapping AS (
    SELECT
        p.payment_id,
        p.payment_date,
        p.amount,
        s.plan_id
    FROM payments AS p
    INNER JOIN subscriptions AS s
        ON p.customer_id = s.customer_id
       AND p.payment_date >= s.subscription_start_date
       AND (
            s.subscription_end_date IS NULL
            OR p.payment_date < s.subscription_end_date
       )
    WHERE p.payment_status = 'Success'
)

SELECT
    sp.plan_name,
    DATE_TRUNC('month', ppm.payment_date)::DATE AS revenue_month,
    SUM(ppm.amount) AS total_monthly_revenue,
    AVG(ppm.amount) AS average_payment_amount,
    COUNT(ppm.payment_id) AS successful_payment_count
FROM payment_plan_mapping AS ppm
INNER JOIN subscription_plans AS sp
    ON ppm.plan_id = sp.plan_id
GROUP BY
    sp.plan_name,
    DATE_TRUNC('month', ppm.payment_date)
ORDER BY
    revenue_month,
    total_monthly_revenue DESC;

-- Q03: What is the overall customer churn rate?
-- ============================================================
SELECT
    COUNT(*) AS total_customers,

    COUNT(*) FILTER (
        WHERE churned IS TRUE
    ) AS churned_customers,

    COUNT(*) FILTER (
        WHERE churned IS FALSE
    ) AS non_churned_customers,

    ROUND(
        100.0 * COUNT(*) FILTER (
            WHERE churned IS TRUE
        ) / NULLIF(COUNT(*), 0),
        2
    ) AS overall_churn_rate_percent

FROM churn_labels;

-- Q38: What is the churn rate by subscription plan?
-- ============================================================
WITH customer_plan AS (
    SELECT
        cl.customer_id,
        cl.churned,
        s.plan_id,

        ROW_NUMBER() OVER (
            PARTITION BY cl.customer_id
            ORDER BY s.subscription_start_date DESC
        ) AS rn

    FROM churn_labels AS cl

    INNER JOIN subscriptions AS s
        ON cl.customer_id = s.customer_id

    WHERE
        (
            cl.churned IS TRUE
            AND cl.churn_date >= s.subscription_start_date
            AND (
                s.subscription_end_date IS NULL
                OR cl.churn_date < s.subscription_end_date
            )
        )
        OR
        (
            cl.churned IS FALSE
            AND s.subscription_start_date = (
                SELECT MAX(s2.subscription_start_date)
                FROM subscriptions AS s2
                WHERE s2.customer_id = cl.customer_id
            )
        )
),

plan_churn AS (
    SELECT
        customer_id,
        plan_id,
        churned
    FROM customer_plan
    WHERE rn = 1
)

SELECT
    sp.plan_name,
    COUNT(*) AS total_customers,

    COUNT(*) FILTER (
        WHERE pc.churned IS TRUE
    ) AS churned_customers,

    COUNT(*) FILTER (
        WHERE pc.churned IS FALSE
    ) AS non_churned_customers,

    ROUND(
        100.0 * COUNT(*) FILTER (
            WHERE pc.churned IS TRUE
        ) / NULLIF(COUNT(*), 0),
        2
    ) AS churn_rate_percent

FROM plan_churn AS pc

INNER JOIN subscription_plans AS sp
    ON pc.plan_id = sp.plan_id

GROUP BY sp.plan_name
ORDER BY churn_rate_percent DESC;

-- Q04: Which acquisition channel has the most customers
-- and what is the churn rate by acquisition channel?
-- =====================================================
SELECT
    COALESCE(NULLIF(TRIM(c.acquisition_channel), ''), 'Unknown')
        AS acquisition_channel,

    COUNT(DISTINCT c.customer_id) AS total_customers,

    COUNT(DISTINCT c.customer_id)
        FILTER (WHERE cl.churned = TRUE) AS churned_customers,

    ROUND(
        COUNT(DISTINCT c.customer_id)
            FILTER (WHERE cl.churned = TRUE) * 100.0
        / NULLIF(COUNT(DISTINCT c.customer_id), 0),
        2
    ) AS churn_rate_pct

FROM customers c
INNER JOIN churn_labels cl
    ON c.customer_id = cl.customer_id

GROUP BY 1
ORDER BY total_customers DESC;

