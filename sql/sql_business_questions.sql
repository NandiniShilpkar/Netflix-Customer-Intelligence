SELECT
    acquisition_channel,
    COUNT(*) AS acquired_customers,
    SUM(is_active) AS currently_active_customers,
    ROUND(SUM(is_active) * 100.0 / NULLIF(COUNT(*), 0), 2)
        AS retention_rate_pct
FROM customer_status
GROUP BY acquisition_channel
ORDER BY retention_rate_pct DESC;

-- Q26: Customer lifetime spend and NTILE(4) quartiles
